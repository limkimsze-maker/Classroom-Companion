const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const make=require('./helpers/handwriting-context.cjs'),{assemble}=require('./benchmark-handwriting-simulations.cjs');
const ctx=make();vm.runInContext(fs.readFileSync('scripts/handwriting-uji-real-ink-fixtures.js','utf8'),ctx);
const model=ctx.WhiteboardHandwritingContext,reader=ctx.WhiteboardHandwritingMath;
const ink=(writer,text,rep=0)=>assemble(ctx.WhiteboardUJIInkFixtures.samples[writer],text,rep);
(async()=>{
 assert.equal(model.info().samples,48000);
 assert(model.score('97 kg')>model.score('97 k9'),'notation statistics favour a complete unit');
 assert.equal(model.score('6 − 2 = 4'),model.score('6 − 2 = 5'),'mathematical truth cannot affect the model score');
 assert.equal(model.score('8 × 2 = 999'),model.score('8 × 2 = 16'),'numerical values and answer length are neutral');
 const quantity=ink('4','97kg',1);
 const before=await reader.recognize(quantity,1800,600,{mode:'auto',context:false});
 const after=await reader.recognize(quantity,1800,600,{mode:'auto'});
 assert.notEqual(before.text.replace(/\s/g,''),'97kg');
 assert.equal(after.text,'97 kg');assert.equal(after.engine,'local-context-language-model');
 assert(after.context.applied);assert(after.uncertain.length,'context corrections require preview review');
 assert(after.context.alternatives.some(a=>a.text===before.text),'original reading remains available');
 const covered=new Set(after.tokens.flatMap(t=>(t.parts||[]).map(p=>p.source)).filter(Boolean));
 assert.equal(covered.size,quantity.length,'the proposed reading consumes every selected stroke');
 const wrongSum=await reader.recognize(ink('1','6−2=5'),1800,600,{mode:'auto'});
 assert.equal(wrongSum.text,'6 − 2 = 5','do not turn a written incorrect answer into the mathematically correct one');
 const ordinary=await reader.recognize(ink('1','972'),1800,600,{mode:'auto'});
 assert.equal(ordinary.text,'972','preserve a confident number');
 const personalGlyph=make(),localReader=personalGlyph.WhiteboardHandwritingMath;
 const gCount=ctx.WhiteboardUJIInkFixtures.samples['4'].g[1].length;
 const gRaster=localReader.rasterDigit(quantity.slice(-gCount).map(s=>({size:s.size,points:s.points.map(p=>({x:p.x*1800,y:p.y*600}))})));
 personalGlyph.WhiteboardHandwritingLearning.match=pixels=>pixels.every((v,i)=>v===gRaster[i])?{char:'q',score:.98,personal:true}:null;
 const glyphBefore=await localReader.recognize(quantity,1800,600,{mode:'auto',context:false});
 assert.equal((await localReader.recognize(quantity,1800,600,{mode:'auto'})).text,glyphBefore.text,'context also preserves a confirmed individual character in a compound');
 const memory=new Map(),personal=make(memory),tr=personal.WhiteboardHandwritingMath;
 const tx=personal.WhiteboardHandwritingLearning.confirm(before,'97 k9',tr.rasterDigit,quantity,1800,600,'auto');
 assert(tx?.count);const fixed=await tr.recognize(quantity,1800,600,{mode:'auto'});
 assert.equal(fixed.text,'97 k9');assert.equal(fixed.engine,'local-personal-ink','context cannot override a confirmed correction');
 ctx.WhiteboardHandwritingContext={...model,rank(){throw Error('unavailable context')}};
 assert.equal((await reader.recognize(quantity,1800,600,{mode:'auto'})).text,before.text,'a context failure retains the completed original reading');
 console.log('PASS learned notation context: real development ink, full coverage, review alternatives, personal priority, arithmetic preservation, failure fallback');
})().catch(e=>{console.error(e);process.exitCode=1});
