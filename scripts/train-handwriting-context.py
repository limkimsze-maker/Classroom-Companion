"""Fit a small notation language model without reading any pen/test fixtures.

Synthetic operands and answers are independent: mathematical truth is never a
training signal. The resulting counts are a statistical language model, not an
LLM or a replacement for the existing handwriting classifiers.
"""
import collections
import hashlib
import json
import pathlib
import random
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
UNITS = ['m', 'mm', 'cm', 'km', 'g', 'kg', 'mg', 'ml', 'L', 's', 'min', 'h']
POWERS = [u + p for u in ['m', 'mm', 'cm', 'km'] for p in ['²', '³']]

def normalize(text):
    return re.sub(r'\d+(?:\.\d+)?', '#', re.sub(r'\s+', '', text)).replace('-', '−')

def fit(seed=20261020, repetitions=600):
    rng = random.Random(seed)
    counts = [collections.Counter() for _ in range(3)]
    corpus = []
    units = UNITS + POWERS
    for _ in range(repetitions):
        for unit in units:
            operands = [str(rng.randrange(10000)) for _ in range(5)]
            if rng.random() < .3:
                operands[0] += '.' + str(rng.randrange(100))
            op = rng.choice(['+', '−', '×', '÷'])
            # Do not solve the expression or make its answer more probable.
            corpus.extend([operands[0], operands[0] + unit,
                           operands[0] + op + operands[1] + '=' + operands[2],
                           operands[0] + op + operands[1] + '=' + operands[2] + unit])
    for text in corpus:
        value = '^^' + normalize(text) + '$'
        for i in range(2, len(value)):
            for order in range(3):
                counts[order][value[i-order:i+1]] += 1
    vocabulary = sorted({key for key in counts[0]})
    return {'schema': 'classroom-notation-language-model-v1', 'seed': seed,
            'samples': len(corpus), 'units': UNITS, 'poweredUnits': POWERS,
            'vocabulary': vocabulary, 'counts': [dict(sorted(c.items())) for c in counts],
            'corpusSha256': hashlib.sha256('\n'.join(corpus).encode()).hexdigest(),
            'method': 'Character trigram counts fitted to generated numeric notation. No pen fixtures, writer IDs, benchmark labels or arithmetic correctness used.'}

if __name__ == '__main__':
    model = fit()
    path = ROOT / 'whiteboard-handwriting-context-model-beta.js'
    path.write_text('/* Generated by scripts/train-handwriting-context.py; no pen data. */\n'
                    'window.WhiteboardHandwritingContextModel=Object.freeze('
                    + json.dumps(model, ensure_ascii=False, separators=(',', ':')) + ');\n')
    print(json.dumps({'samples': model['samples'], 'bytes': path.stat().st_size,
                      'corpusSha256': model['corpusSha256']}))
