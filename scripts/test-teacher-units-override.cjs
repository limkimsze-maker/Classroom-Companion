const fs=require('fs'),vm=require('vm'),assert=require('assert');
for(const f of ['whiteboard-teacher-units-beta.js','whiteboard-handwriting-recognition-beta.js'])new vm.Script(fs.readFileSync(f,'utf8'),{filename:f});
const ctx={window:{},atob,Float32Array,Math};vm.createContext(ctx);
vm.runInContext(fs.readFileSync('whiteboard-teacher-units-beta.js','utf8'),ctx);
const info=ctx.window.WhiteboardTeacherUnits.info();
assert.equal(info.sourceSamples,1024);
assert.equal(info.trainedLabels.length,50);
assert(!info.trainedLabels.includes('='));
for(const name of ['cm²','cm³','kg','×','÷','²','³'])assert(info.trainedLabels.includes(name),name);
for(const name of ['l','s','h','hr','am','pm','S$','/','*',','])assert(!info.trainedLabels.includes(name),name);
const sample=[{points:[{x:.2,y:.2},{x:.3,y:.3},{x:.4,y:.4}]}];
const result=ctx.window.WhiteboardTeacherUnits.rank(sample,320,285);
assert(Array.isArray(result));
const reader=fs.readFileSync('whiteboard-handwriting-recognition-beta.js','utf8');
assert(reader.includes("teacher.match(strokes,W,H"));
assert(reader.includes("readMeasuredDigits(items,W,H)"));
const html=fs.readFileSync('whiteboard-comer-beta.html','utf8');
assert(html.indexOf('whiteboard-teacher-units-beta.js')<html.indexOf('whiteboard-handwriting-recognition-beta.js'));
console.log('PASS 1024-source prototype shape, trained label precedence and no equals regression');
